// Base path — works with XAMPP at /helpdesk/
const BASE = window.location.pathname.split('/').slice(0, 2).join('/');
const API  = `${BASE}/api`;

function getLang()  { return localStorage.getItem('lang')  || 'en'; }
function getTheme() { return localStorage.getItem('theme') || 'dark'; }
function getUser()  { return JSON.parse(localStorage.getItem('user') || 'null'); }

function setLang(lang) { localStorage.setItem('lang', lang); applyLang(lang); }
function setTheme(theme) { localStorage.setItem('theme', theme); applyTheme(theme); }

function applyLang(lang) {
  document.documentElement.lang = lang;
  document.body.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (i18n[lang][key]) el.textContent = i18n[lang][key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (i18n[lang][key]) el.placeholder = i18n[lang][key];
  });
}

function applyTheme(theme) {
  document.documentElement.setAttribute('data-theme', theme);
}

function t(key) { return i18n[getLang()][key] || key; }

async function apiFetch(endpoint, options = {}) {
  const headers = { 'Content-Type': 'application/json', ...(options.headers || {}) };
  try {
    const res = await fetch(`${API}${endpoint}`, { ...options, headers, credentials: 'include' });
    const data = await res.json();
    if (res.status === 401) {
      localStorage.removeItem('user');
      window.location.href = `${BASE}/index.php`;
    }
    return { ok: res.ok, status: res.status, data };
  } catch(e) {
    return { ok: false, status: 0, data: { message: 'Network error. Is the server running?' } };
  }
}

async function requireAuth() {
  const user = getUser();
  if (!user) {
    window.location.href = `${BASE}/index.php`;
    return;
  }
  // Verify session is still valid
  const { ok } = await apiFetch('/auth/me.php');
  if (!ok) {
    localStorage.removeItem('user');
    window.location.href = `${BASE}/index.php`;
  }
}

function redirectIfAuth() {
  const user = getUser();
  if (user) window.location.href = `${BASE}/pages/${landingPage(user.role)}`;
}

function landingPage(role) {
  return role === 'user' ? 'home.php' : 'dashboard.php';
}

async function logout() {
  await apiFetch('/auth/logout.php');
  localStorage.removeItem('user');
  window.location.href = `${BASE}/index.php`;
}

function showAlert(id, msg, type = 'error') {
  const el = document.getElementById(id);
  if (!el) return;
  el.textContent = msg;
  el.className = `alert alert-${type} show`;
  setTimeout(() => el.classList.remove('show'), 4000);
}

function formatDate(dateStr) {
  if (!dateStr) return '—';
  return new Date(dateStr).toLocaleDateString(getLang(), {
    day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit'
  });
}

function statusBadge(status) {
  const map = { 'Open':'open','In Progress':'progress','Resolved':'resolved','Closed':'closed' };
  return `<span class="badge badge-${map[status]||'open'}">${status}</span>`;
}

function priorityBadge(priority) {
  const map = { 'Low':'low','Medium':'medium','High':'high','Critical':'critical' };
  return `<span class="badge badge-${map[priority]||'low'}">${priority}</span>`;
}

document.addEventListener('DOMContentLoaded', () => {
  applyTheme(getTheme());
  applyLang(getLang());
});
